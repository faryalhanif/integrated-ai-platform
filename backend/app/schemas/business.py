from datetime import datetime, timezone
from typing import Any, Dict, List, Literal, Optional

from pydantic import BaseModel, Field, HttpUrl


class BusinessSubmission(BaseModel):
    """
    Raw onboarding data submitted by the client.

    Keep this close to the "5-minute setup" onboarding: a data source
    plus a short description of the business. Everything else is
    optional and, if omitted, is either auto-inferred by the
    BusinessProfileAgent (e.g. suggested sections) or auto-defaulted by
    the platform (e.g. fallback_message) — never hardcoded per-business
    in code.

    NOTE: document/URL ingestion into the knowledge base itself is
    handled by the separate ingestion pipeline (teammate's part). This
    schema only carries what's needed to build the business profile and
    the chatbot's system prompt.
    """

    business_name: str = Field(
        ...,
        min_length=2,
        max_length=200,
        description="Business or company name.",
    )

    business_description: str = Field(
        ...,
        min_length=20,
        description="Brief description of the business, its products/services.",
    )

    target_audience: str = Field(
        ...,
        min_length=2,
        description="Who is the chatbot / website intended for?",
    )

    brand_tone: str = Field(
        ...,
        min_length=2,
        description="e.g. Friendly & Casual, Strictly Professional, Technical & Precise, Sales-Oriented.",
    )

    website_url: Optional[HttpUrl] = Field(
        default=None,
        description="Business website, used to auto-extract brand colors/logo/sections.",
    )

    # ---------------------------------
    # MVP scope: only Customer Support is supported today.
    # Kept as a locked literal (rather than a free string) so the field
    # is self-documenting and future goals (lead_generation,
    # technical_support, ...) can be added later without touching the
    # RAG pipeline logic, which currently only implements this one mode.
    # ---------------------------------
    primary_goal: Literal["customer_support"] = Field(
        default="customer_support",
        description="Bot's primary purpose. Only 'customer_support' is supported in this MVP.",
    )

    fallback_message: Optional[str] = Field(
        default=None,
        description=(
            "What the bot should say when it doesn't know the answer. "
            "If omitted, the platform generates a safe generic default."
        ),
    )

    escalation_contact: Optional[str] = Field(
        default=None,
        description="Email address or link to hand off to a human when the bot can't help.",
    )

    restricted_topics: List[str] = Field(
        default_factory=list,
        description="Topics the bot must never discuss (e.g. pricing negotiations, legal advice, competitor comparisons).",
    )

    brand_colors: Optional[Dict[str, str]] = Field(
        default=None,
        description="Optional explicit brand colors, e.g. {'primary': '#123456'}. Auto-extracted from website_url if omitted.",
    )

    logo_url: Optional[HttpUrl] = Field(
        default=None,
        description="Optional logo URL.",
    )

    knowledge_base_id: Optional[str] = Field(
        default=None,
        description=(
            "Identifier of this project's knowledge base collection, as "
            "created by the ingestion pipeline. If omitted, defaults to "
            "the generated project_id."
        ),
    )


class BusinessProfile(BaseModel):
    """
    Structured business profile generated by the Business Profile Agent.

    This is the project's source of truth: it is persisted and used both
    for website generation and to drive the chatbot's system prompt and
    guardrails at runtime.
    """

    project_id: str = Field(
        ...,
        description="Unique project identifier.",
    )

    business_name: str

    business_description: str

    target_audience: str

    brand_tone: str

    website_url: Optional[HttpUrl] = None

    primary_goal: Literal["customer_support"] = "customer_support"

    fallback_message: Optional[str] = Field(
        default=None,
        description="May be empty; the platform fills in a default if so.",
    )

    escalation_contact: Optional[str] = None

    restricted_topics: List[str] = Field(default_factory=list)

    brand_colors: Optional[Dict[str, str]] = None

    logo_url: Optional[HttpUrl] = None

    knowledge_base_id: Optional[str] = None

    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Server-assigned creation timestamp (UTC, ISO 8601).",
    )

    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Auto-generated metadata such as industry, primary language, "
            "suggested website sections, keywords, etc."
        ),
    )